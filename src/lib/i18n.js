export function isSupportedLang(lang) {
  return LANG_IDS.has(lang);
}

export function htmlLangFor(lang) {
  return LANGUAGES.find((l) => l.id === lang)?.htmlLang || 'en';
}

export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS[DEFAULT_LANG];
  const template = table[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (
    vars[name] == null ? `{${name}}` : String(vars[name])
  ));
}

export function loadLang(storage = typeof localStorage !== 'undefined' ? localStorage : null) {
  if (!storage) return DEFAULT_LANG;
  try {
    const saved = storage.getItem(LANG_KEY);
    if (isSupportedLang(saved)) return saved;
  } catch {
    // ignore
  }
  return DEFAULT_LANG;
}

export function saveLang(lang, storage = typeof localStorage !== 'undefined' ? localStorage : null) {
  if (!storage || !isSupportedLang(lang)) return false;
  try {
    storage.setItem(LANG_KEY, lang);
    return true;
  } catch {
    return false;
  }
}

export function applyDocumentLang(lang, doc = typeof document !== 'undefined' ? document : null) {
  if (!doc?.documentElement) return;
  doc.documentElement.lang = htmlLangFor(lang);
}
